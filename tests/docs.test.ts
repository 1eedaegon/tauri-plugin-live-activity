// The documents hold together: a link of a Markdown file names a file that is tracked and, with an anchor, a heading
// that the file has; a picture that a document shows is tracked; a picture under docs/images is named by a document
// or by a record; and every document is linked from another. The test reads the tracked files as text and needs no
// package: the Specification job runs it for every change, a change of the documents alone among them.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { posix } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

/** The repository as the check reads it: the paths that are tracked, and the text of each document and record. */
interface Repository {
  readonly tracked: ReadonlySet<string>;
  /** The text of each Markdown file, by its path. */
  readonly documents: ReadonlyMap<string, string>;
  /** The text of each record that may name a picture, by its path. */
  readonly records: ReadonlyMap<string, string>;
}

/** What a link names in the repository: a path, which is empty for the repository's own folder, and an anchor. */
interface Named {
  readonly path: string;
  readonly anchor: string;
}

const BLOB = /^https:\/\/github\.com\/1eedaegon\/tauri-plugin-live-activity\/(?:blob|tree|raw)\/main\/?(.*)$/;
const RAW = 'https://raw.githubusercontent.com/1eedaegon/tauri-plugin-live-activity/main/';
/** The documents that need no link from another: the page of the repository, and what Tauri's build writes. */
const ENTRIES: ReadonlySet<string> = new Set(['README.md', 'permissions/autogenerated/reference.md']);
/**
 * The pictures that stay though nothing in the tree names them: the READMEs of the four alphas, as npm and crates.io
 * show them to this day, load these two from main.
 */
const KEPT: ReadonlySet<string> = new Set(['docs/images/android-live-activity.png', 'docs/images/android-notification-fallback.png']);
/** What a page shows for the entities that a heading may hold. */
const ENTITIES: Readonly<Record<string, string>> = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ' };

/** `part` with a blank for each of its characters but the ends of its lines: what follows it keeps its place. */
const blank = (part: string): string => part.replace(/[^\n]/g, ' ');

/** A document without its fenced code, line for line. A fence of backticks or tildes ends at one of its kind as long. */
function unfenced(text: string): string {
  let fence: string | undefined;
  return text.split('\n').map(line => {
    const mark = /^ {0,3}(`{3,}|~{3,})/.exec(line)?.[1];
    if (fence === undefined) {
      fence = mark;
      return mark === undefined ? line : '';
    }
    if (mark !== undefined && mark.startsWith(fence) && line.trim() === mark) fence = undefined;
    return '';
  }).join('\n');
}

const COMMENT = /<!--[\s\S]*?-->/g;

/**
 * What a document says outside code and comments, with every other character at its place: fenced code is gone, and
 * a comment of the HTML and a code span are blanks. A span begins and ends at as many backticks, within one paragraph.
 */
function prose(text: string): string {
  return unfenced(text).replace(COMMENT, blank).replace(/(?<!`)(`+)(?!`)(?:(?!\n[ \t\r]*\n)[\s\S])*?(?<!`)\1(?!`)/g, blank);
}

/** A heading as the page shows it: its code as it is written, and of the rest the text, with no tag, mark or entity. */
function shown(heading: string): string {
  // Every second part is a code span.
  return heading.split(/(`+[^`]+`+)/).map((part, at) => at % 2 === 1 ? part.replace(/^`+|`+$/g, '') : part
    .replace(/!?\[([^\]]*)\](?:\([^)]*\)|\[[^\]]*\])/g, '$1')
    .replace(/<[^>]+>/g, '')
    .replace(/(?<![\p{L}\p{N}])(\*{1,3}|_{1,3}|~~)(?=\S)(.+?)(?<=\S)\1(?![\p{L}\p{N}])/gu, '$2')
    .replace(/&([a-z]+);/g, (whole, name: string) => ENTITIES[name] ?? whole)).join('');
}

/** The anchors that GitHub gives the headings of a document, and the ones that the document names itself. */
export function anchors(text: string): ReadonlySet<string> {
  const found = new Set<string>();
  const counts = new Map<string, number>();
  // A comment on one line shows nothing of itself; one over several lines hides the headings on them.
  for (const line of unfenced(text).replace(COMMENT, comment => comment.includes('\n') ? blank(comment) : '').split('\n')) {
    const heading = /^ {0,3}#{1,6}\s+(.*?)\s*#*\s*$/.exec(line)?.[1];
    if (heading === undefined) continue;
    const slug = shown(heading).toLowerCase().replace(/[^\p{L}\p{N}\p{M}_\- ]/gu, '').replace(/ /g, '-');
    // A heading that comes again gets the next number that no anchor has yet.
    let anchor = slug;
    while (found.has(anchor)) {
      const count = (counts.get(slug) ?? 0) + 1;
      counts.set(slug, count);
      anchor = `${slug}-${count}`;
    }
    found.add(anchor);
  }
  for (const match of prose(text).matchAll(/<[a-z][^>]*?\s(?:id|name)=(?:"([^"]+)"|'([^']+)')/gi)) {
    const name = match[1] ?? match[2];
    if (name !== undefined) found.add(name);
  }
  return found;
}

/** The addresses that the links, the pictures and the named links of a document give, each with its place in `body`. */
function targets(body: string): { readonly target: string; readonly at: number }[] {
  const forms = [
    // [text](address), with a title in any of its three forms or without one. Between angle brackets the address
    // may have blanks and parentheses.
    /\]\(\s*(?:<([^>\n]*)>|([^)\s<]+))(?:\s+(?:"[^"]*"|'[^']*'|\([^)]*\)))?\s*\)/g,
    /(?:src|href)=(?:"([^"]+)"|'([^']+)')/g,
    // [name]: address, on a line of its own; a footnote is defined the same way and names no address.
    /^ {0,3}\[(?!\^)[^\]\n]+\]:\s*(?:<([^>\n]*)>|(\S+))/gm,
  ];
  return forms.flatMap(form => [...body.matchAll(form)].map(match => ({ target: match[1] ?? match[2] ?? '', at: match.index })))
    .sort((one, other) => one.at - other.at);
}

/** A part of an address with its escapes read, or nothing when they cannot be read. */
function decoded(part: string): string | undefined {
  try { return decodeURIComponent(part); } catch { return undefined; }
}

/**
 * What a link of `document` names in the repository. Nothing for a link that leaves it, with a scheme or with a host,
 * and `unreadable` for an address whose escapes cannot be read. What follows a question mark is no part of the path:
 * it asks for another view of the file, whose anchors are not the headings', so an anchor after it is not judged.
 */
function named(document: string, target: string): Named | 'unreadable' | undefined {
  const onGitHub = target.startsWith(RAW) ? target.slice(RAW.length) : BLOB.exec(target)?.[1];
  const inside = onGitHub ?? (/^(?:[a-z][a-z0-9+.-]*:|\/\/)/i.test(target) ? undefined : target);
  if (inside === undefined) return undefined;
  const [address = '', fragment = ''] = inside.split('#');
  const [asked = '', ...view] = address.split('?');
  const [file, anchor] = [decoded(asked), view.length > 0 ? '' : decoded(fragment)];
  if (file === undefined || anchor === undefined) return 'unreadable';
  if (file === '' && onGitHub === undefined) return { path: document, anchor };
  // An address on GitHub and a path that begins with a slash start at the repository's folder, any other at the document's.
  const from = onGitHub !== undefined || file.startsWith('/') ? '' : posix.dirname(document);
  const path = posix.normalize(posix.join(from, file)).replace(/^\/+|\/+$/g, '');
  return { path: path === '.' ? '' : path, anchor };
}

/** Every way in which the documents of `repository` do not hold together, one line each. */
export function problems(repository: Repository): string[] {
  const { tracked, documents, records } = repository;
  const folders = new Set([...tracked].flatMap(path => path.split('/').slice(0, -1).map((_, depth, parts) => parts.slice(0, depth + 1).join('/'))));
  const headings = new Map<string, ReadonlySet<string>>();
  const found: string[] = [];
  const linked = new Set<string>();
  const pictured = new Set<string>();
  for (const [document, text] of documents) {
    const body = prose(text);
    for (const { target, at } of targets(body)) {
      const where = `${document}:${body.slice(0, at).split('\n').length}: ${target}`;
      const meant = named(document, target);
      if (meant === undefined) continue;
      if (meant === 'unreadable') { found.push(`${where} is no address that can be read`); continue; }
      // A link to a folder is a link to the document that GitHub shows for it, where the folder has one.
      const folder = meant.path === '' || folders.has(meant.path);
      const path = folder ? posix.join(meant.path, 'README.md') : meant.path;
      if (!tracked.has(path)) {
        if (!folder) found.push(`${where} names no tracked file`);
        continue;
      }
      const other = documents.get(path);
      if (other === undefined) { pictured.add(path); continue; }
      if (path !== document) linked.add(path);
      if (meant.anchor === '') continue;
      const known = headings.get(path) ?? anchors(other);
      headings.set(path, known);
      if (!known.has(meant.anchor)) found.push(`${where} names no heading of ${path}`);
    }
  }
  for (const document of documents.keys()) {
    if (!linked.has(document) && !ENTRIES.has(document)) found.push(`${document}: no document links to it`);
  }
  const texts = [...documents.values(), ...records.values()];
  for (const path of tracked) {
    if (!path.startsWith('docs/images/') || pictured.has(path) || KEPT.has(path)) continue;
    // The name as a whole: one that only ends another file's name, or begins it, is not named.
    const name = new RegExp(`(?<![\\w.-])${posix.basename(path).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?![\\w-]|\\.\\w)`);
    if (!texts.some(text => name.test(text))) found.push(`${path}: no document shows it and no record names it`);
  }
  return found;
}

/** A repository of the test's own: `files` by path, of which the Markdown files are its documents. */
function repository(files: Readonly<Record<string, string>>): Repository {
  const entries = Object.entries(files);
  return {
    tracked: new Set(Object.keys(files)),
    documents: new Map(entries.filter(([path]) => path.endsWith('.md'))),
    records: new Map(entries.filter(([path]) => path.endsWith('.json'))),
  };
}

// TP-CI-8
test('a link that names no tracked file, no heading or no tracked picture is a problem, and so is what nothing names', () => {
  const sound = {
    'README.md': '# Plugin\n\n[Guide](docs/guide.md#set-up-by-hand) and the [docs](docs), with <img src="docs/images/card.png">.\n',
    'docs/README.md': '# Docs\n\n[Guide](guide.md)\n',
    'docs/guide.md': '# Guide\n\n## Set up by hand\n\n## Set up by hand\n\n[again](#set-up-by-hand-1), [`code` and more](#code-and-more)\n\n### `code` and more\n\n```md\n[not a link](missing.md)\n```\n',
    'docs/images/card.png': '',
  };
  assert.deepEqual(problems(repository(sound)), []);
  const broken = (changed: Readonly<Record<string, string>>): string[] => problems(repository({ ...sound, ...changed }));
  assert.deepEqual(broken({ 'README.md': '[Guide](docs/guide.md) [docs](docs) [gone](docs/gone.md) <img src="docs/images/card.png">' }),
    ['README.md:1: docs/gone.md names no tracked file']);
  assert.deepEqual(broken({ 'docs/README.md': '# Docs\n\n[Guide](guide.md#set-up)\n' }),
    ['docs/README.md:3: guide.md#set-up names no heading of docs/guide.md']);
  assert.deepEqual(broken({ 'README.md': '[Guide](docs/guide.md) [docs](docs) <img src="docs/images/other.png">' }),
    ['README.md:1: docs/images/other.png names no tracked file', 'docs/images/card.png: no document shows it and no record names it']);
  assert.deepEqual(broken({ 'docs/notes.md': '# Notes\n' }), ['docs/notes.md: no document links to it']);
  // A record that names a picture keeps it, and a link to this repository on GitHub is read as a link within it.
  assert.deepEqual(broken({
    'README.md': '[Guide](https://github.com/1eedaegon/tauri-plugin-live-activity/blob/main/docs/guide.md#guide) [docs](https://github.com/1eedaegon/tauri-plugin-live-activity/tree/main/docs)',
    'tests/results/shots.json': '{ "path": "docs/images/card.png" }',
  }), []);
  assert.deepEqual(broken({ 'README.md': '[Guide](https://github.com/1eedaegon/tauri-plugin-live-activity/blob/main/docs/guide.md#gone) [docs](docs) ![card](https://raw.githubusercontent.com/1eedaegon/tauri-plugin-live-activity/main/docs/images/card.png)' }),
    ['README.md:1: https://github.com/1eedaegon/tauri-plugin-live-activity/blob/main/docs/guide.md#gone names no heading of docs/guide.md']);
  // A name is a whole name: a record of big-card.png or of card.png.old keeps neither card.png, and a file of any kind
  // under docs/images is a picture.
  const unshown = '[Guide](docs/guide.md) [docs](docs)';
  assert.deepEqual(broken({ 'README.md': unshown, 'tests/results/shots.json': '{ "paths": ["docs/images/big-card.png", "card.png.old"] }' }),
    ['docs/images/card.png: no document shows it and no record names it']);
  assert.deepEqual(broken({ 'README.md': `${unshown} and card.png.`, 'docs/images/card.svg': '' }),
    ['docs/images/card.svg: no document shows it and no record names it']);
});

// TP-CI-8
test('what stands in code or in a comment is no link, no heading and no anchor', () => {
  const page = (body: string): string[] => problems(repository({ 'README.md': `# Plugin\n\n${body}\n` }));
  assert.deepEqual(page('```md\n[gone](gone.md)\n```'), []);
  assert.deepEqual(page('~~~\n[gone](gone.md)\n~~~'), []);
  // A fence ends at one of its own kind that is as long: the three backticks within four are code.
  assert.deepEqual(page('````md\n```\n[gone](gone.md)\n```\n````\n\n[there](#plugin)'), []);
  assert.deepEqual(page('Write `[text](gone.md)`, call `handlers[kind](event)` or use ``<a href="gone.md">`` so.'), []);
  assert.deepEqual(page('<!-- [gone](gone.md)\n<img src="gone.png"> -->'), []);
  // What follows the code is read, and at its own line.
  assert.deepEqual(page('`[text](gone.md)` and [gone](gone.md)\n\n```\ncode\n```\n\n[gone](other.md)'),
    ['README.md:3: gone.md names no tracked file', 'README.md:9: other.md names no tracked file']);
  // A stray backtick hides nothing beyond its paragraph, whichever way the file ends its lines.
  assert.deepEqual(page('A ` alone.\n\n[gone](gone.md) and `code`'), ['README.md:5: gone.md names no tracked file']);
  assert.deepEqual(page('A ` alone.\r\n\r\n[gone](gone.md) and `code`'), ['README.md:5: gone.md names no tracked file']);
  assert.deepEqual([...anchors('# One\n\n```md\n## In a fence\n<a id="fenced"></a>\n```\n\n`<a id="spanned">`\n\n<!--\n## In a comment\n-->\n\n<a id="named"></a> <span id=\'spanned-too\'></span>\n')],
    ['one', 'named', 'spanned-too']);
});

// TP-CI-8
test('the anchor of a heading is the one GitHub gives the text that the page shows', () => {
  const anchor = (heading: string): string[] => [...anchors(heading)];
  assert.deepEqual(anchor('## Set up by hand'), ['set-up-by-hand']);
  assert.deepEqual(anchor('## 0.2.0 validation (earlier)'), ['020-validation-earlier']);
  assert.deepEqual(anchor('## 설치와 설정'), ['설치와-설정']);
  assert.deepEqual(anchor('## The [guide](guide.md) and the [index][docs]'), ['the-guide-and-the-index']);
  // Code shows as it is written, also where it looks like a tag; outside code a tag shows nothing.
  assert.deepEqual(anchor('## `Option<T>` and the `<name>` field'), ['optiont-and-the-name-field']);
  assert.deepEqual(anchor('## A <b>bold</b> word'), ['a-bold-word']);
  assert.deepEqual(anchor('## A &amp; B'), ['a--b']);
  assert.deepEqual(anchor('## Use _this_, **that** and snake_case'), ['use-this-that-and-snake_case']);
  assert.deepEqual(anchor('   ## Indented ##'), ['indented']);
  assert.deepEqual(anchor('## Twice\n\n## Twice\n\n## Twice'), ['twice', 'twice-1', 'twice-2']);
  // A number that a heading already has is passed over.
  assert.deepEqual(anchor('## Twice\n\n## Twice 1\n\n## Twice'), ['twice', 'twice-1', 'twice-2']);
  // A comment within a heading shows nothing, and leaves no blanks.
  assert.deepEqual(anchor('## Foo <!-- note --> Bar'), ['foo--bar']);
});

// TP-CI-8
test('a link is read in each form that Markdown and GitHub take', () => {
  const files = { 'README.md': '# Plugin\n\n[Guide](docs/guide.md) [Korean](docs/ko.md)\n', 'docs/guide.md': '# Guide\n\n## Set up\n', 'docs/ko.md': '# 안내\n\n## 설치\n', 'docs/images/card.png': '' };
  const guide = (body: string): string[] => problems(repository({ ...files, 'docs/guide.md': `# Guide\n\n## Set up\n\n<img src="images/card.png">\n\n${body}\n` }));
  // A title, in any of its three forms, is no part of the address.
  assert.deepEqual(guide(`[a](gone.md "title") [b](gone.md 'title') [c](gone.md (title)) [d](<gone.md>)`), [1, 2, 3, 4].map(() => 'docs/guide.md:7: gone.md names no tracked file'));
  // Between angle brackets an address may have blanks and parentheses.
  assert.deepEqual(guide('[a](<a file (old).md> "title") [b](<ko.md>)'), ['docs/guide.md:7: a file (old).md names no tracked file']);
  assert.deepEqual(guide(`<a href='gone.md'>a</a> <img src='images/gone.png'>`),
    ['docs/guide.md:7: gone.md names no tracked file', 'docs/guide.md:7: images/gone.png names no tracked file']);
  // A link by a name, with the name defined on a line of its own; a footnote is no such definition.
  assert.deepEqual(guide('[the index][index] and a note[^1]\n\n[index]: ../README.md#plugin\n[gone]: <gone.md> "title"\n[^1]: gone.md is a word here'),
    ['docs/guide.md:10: gone.md names no tracked file']);
  // From the repository's folder: a path that begins with a slash, and the folder itself.
  assert.deepEqual(guide('[a](/docs/ko.md) [b](/README.md#plugin) [c](../) [d](../#plugin) [e](/gone.md) [f](../#gone)'),
    ['docs/guide.md:7: /gone.md names no tracked file', 'docs/guide.md:7: ../#gone names no heading of README.md']);
  // What follows a question mark is no part of the path. It asks GitHub for another view of the file, whose anchors
  // are not the headings', so an anchor after it is not judged. An anchor may be written with escapes.
  assert.deepEqual(guide('[a](ko.md?plain=1#L3) [b](ko.md#%EC%84%A4%EC%B9%98) [c](ko.md#%EC%84%A4) [d](../README.md?plain=1) [e](gone.md?plain=1#L3)'),
    ['docs/guide.md:7: ko.md#%EC%84%A4 names no heading of docs/ko.md', 'docs/guide.md:7: gone.md?plain=1#L3 names no tracked file']);
  assert.deepEqual(guide('[a](100%.md) [b](ko.md#100%)'),
    ['docs/guide.md:7: 100%.md is no address that can be read', 'docs/guide.md:7: ko.md#100% is no address that can be read']);
  // A folder's anchor is a heading of its README.md.
  assert.deepEqual(problems(repository({ ...files, 'docs/README.md': '# Docs\n\n[a](../docs#docs) [b](.#gone) [c](guide.md) [d](ko.md)\n', 'README.md': '# Plugin\n\n[docs](docs) <img src="docs/images/card.png">\n' })),
    ['docs/README.md:3: .#gone names no heading of docs/README.md']);
  // A picture on GitHub's own address for files is one of the repository, with what follows its name left out.
  assert.deepEqual(guide('![card](https://raw.githubusercontent.com/1eedaegon/tauri-plugin-live-activity/main/docs/images/gone.png?raw=true)'),
    ['docs/guide.md:7: https://raw.githubusercontent.com/1eedaegon/tauri-plugin-live-activity/main/docs/images/gone.png?raw=true names no tracked file']);
  assert.deepEqual(guide('<img src="https://github.com/1eedaegon/tauri-plugin-live-activity/raw/main/docs/images/gone.png">'),
    ['docs/guide.md:7: https://github.com/1eedaegon/tauri-plugin-live-activity/raw/main/docs/images/gone.png names no tracked file']);
  // An address without a scheme and with a host leaves the repository.
  assert.deepEqual(guide('<img src="//example.com/card.png">'), []);
});

// TP-CI-8
test('the documents of the repository hold together', () => {
  const root = fileURLToPath(new URL('..', import.meta.url));
  // With -z a path comes as it is, whatever characters it has.
  const tracked = execFileSync('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8' }).split('\0').filter(path => path !== '');
  const read = (kind: RegExp): Map<string, string> => new Map(tracked.filter(path => kind.test(path)).map(path => [path, readFileSync(posix.join(root, path), 'utf8')]));
  assert.deepEqual(problems({ tracked: new Set(tracked), documents: read(/\.md$/), records: read(/\.json$/) }), []);
});
